"""Generate small synthesizable workload ROM and independent Python expected file."""
import json,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT))
from model.matrix_golden import matmul,encode_csr,matmul_csr

def generate(dest):
    dest=Path(dest);dest.mkdir(parents=True,exist_ok=True)
    b=list(range(-8,8))
    matrices=[[0]*16,[int(i//4==i%4) for i in range(16)],
              [-3,0,0,0, 0,0,0,0, 0,5,0,0, 0,0,-2,7],
              [i-8 if i<8 else i-7 for i in range(16)]]
    cases=[]
    for i,a in enumerate(matrices):
        v,c,p=encode_csr(a);expected=matmul(a,b)
        assert matmul_csr(v,c,p,b)==expected
        cases.append(dict(mode=i,label=['zero','identity','sparse','dense'][i],a=a,b=b,values=v,columns=c,pointers=p,
                          nnz=len(v),nonempty_rows=sum(p[j]!=p[j+1] for j in range(4)),expected=expected))
    text=['// Generated by generate_rom.py; do not hand edit.',
          'module demo_rom(input wire [1:0] mode,input wire [6:0] d_index,s_index,',
          'input wire [3:0] out_addr,output reg [2:0] d_bank,s_bank,',
          'output reg [4:0] d_addr,s_addr,output wire [31:0] d_data,',
          'output reg [31:0] s_data,output wire [6:0] d_total,s_total,',
          'output wire [31:0] expected,output reg [4:0] nnz);']
    def fn(name,width,bits,items):
        text.extend([f'function [{width-1}:0] {name};',f'input [{bits-1}:0] key;', 'begin case(key)'])
        for k,val in items:text.append(f"{bits}'d{k}: {name}={width}'h{val&((1<<width)-1):x};")
        text.extend([f'default: {name}=0;', 'endcase end endfunction'])
    for name,w,field in [('rom_a',8,'a'),('rom_v',8,'values'),('rom_c',2,'columns'),('rom_expected',32,'expected')]:
        fn(name,w,6,[(x['mode']*16+j,v) for x in cases for j,v in enumerate(x[field])])
    fn('rom_b',8,4,list(enumerate(b)))
    fn('rom_p',5,5,[(x['mode']*8+j,v) for x in cases for j,v in enumerate(x['pointers'])])
    text += ['always @* begin case(mode)']+[f"2'd{x['mode']}: nnz=5'd{x['nnz']};" for x in cases]+['default:nnz=0;endcase end',
        'wire [6:0] vi_full=s_index-7\'d16;', 'wire [6:0] ci_full=s_index-7\'d16-{2\'b0,nnz};',
        'wire [6:0] pi_full=s_index-7\'d16-{1\'b0,nnz,1\'b0};',
        'wire [3:0] vi=vi_full[3:0],ci=ci_full[3:0];wire [2:0] pi=pi_full[2:0];',
        'wire [7:0] dw=d_index<16 ? rom_a({mode,d_index[3:0]}) : rom_b(d_index[3:0]);',
        'wire [7:0] bv=rom_b(s_index[3:0]);wire [7:0] vv=rom_v({mode,vi});',
        'assign d_data={{24{dw[7]}},dw};assign expected=rom_expected({mode,out_addr});',
        "assign d_total=7'd32;assign s_total=7'd22+{1'b0,nnz,1'b0};",
        'always @* begin',
        'd_bank=d_index<16 ? 3\'d0:3\'d1;d_addr={1\'b0,d_index[3:0]};',
        's_bank=5;s_addr=0;s_data={27\'d0,nnz};',
        "if(s_index<16)begin s_bank=1;s_addr={1'b0,s_index[3:0]};s_data={{24{bv[7]}},bv};end",
        "else if(s_index<7'd16+{2'b0,nnz})begin s_bank=0;s_addr={1'b0,vi};s_data={{24{vv[7]}},vv};end",
        "else if(s_index<7'd16+{1'b0,nnz,1'b0})begin s_bank=3;s_addr={1'b0,ci};s_data={30'd0,rom_c({mode,ci})};end",
        "else if(s_index<7'd21+{1'b0,nnz,1'b0})begin s_bank=4;s_addr={2'b0,pi};s_data={27'd0,rom_p({mode,pi})};end",
        'end endmodule']
    (dest/'demo_rom.sv').write_text('\n'.join(text)+'\n',encoding='ascii')
    (dest/'workloads.json').write_text(json.dumps(cases,indent=2)+'\n')
    lines=[]
    for x in cases:lines += [f"{x['mode']} {x['nnz']} {x['nonempty_rows']}",' '.join(f'{v:08x}' for v in x['expected'])]
    (dest/'expected.txt').write_text('\n'.join(lines)+'\n')
    tb=[]
    for x in cases:
        d=[(0,j,v) for j,v in enumerate(x['a'])]+[(1,j,v) for j,v in enumerate(x['b'])]
        s=[(1,j,v) for j,v in enumerate(x['b'])]+[(0,j,v) for j,v in enumerate(x['values'])]+[(3,j,v) for j,v in enumerate(x['columns'])]+[(4,j,v) for j,v in enumerate(x['pointers'])]+[(5,0,x['nnz'])]
        tb += [f"{x['mode']} {x['nnz']} {x['nonempty_rows']} {len(d)} {len(s)}",' '.join(f'{v:08x}' for v in x['expected'])]
        tb += [f'{bank} {addr} {v&0xffffffff:08x}' for bank,addr,v in d+s]
    (dest/'tb_vectors.txt').write_text('\n'.join(tb)+'\n')
    return cases
if __name__=='__main__':generate(sys.argv[1])
